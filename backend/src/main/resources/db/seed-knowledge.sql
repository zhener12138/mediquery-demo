-- 结构归迁移，数据归人。重复执行会因为主键冲突失败，这是刻意的 ——
-- 数据被覆盖过一次就该有人知道。
--
-- 跑法：
--   mysql -uroot -p mediquery < backend/src/main/resources/db/seed-knowledge.sql
--   （或者粘贴进任何 MySQL 客户端，注意先 USE mediquery;）
--
-- ------------------------------------------------------------
-- 这一版要证明什么
-- ------------------------------------------------------------
-- 改造前：「我拉不出来，蹲半天」→ 切词成「拉不」「不出」「蹲半」「半天」，
--        拿去 MATCH 疾病表的顿号串，一条都命中不了，sources 是空的。
-- 改造后：「拉不出来」归一成症状「排便费力」，「蹲半天」也归一到同一个症状，
--        再用症状 ID 反查 → 便秘。同一句话，从 0 条变成 1 条。
--
-- 反过来说：「我最近总睡不着」这一版仍然是 0 条 —— 因为知识库里
-- 压根没有「失眠」这个病。这是**数据**的缺口，不是链路的问题，
-- 扩充病种是下一步的事。这个区别很重要：链路修好了，补数据才有意义。
--
-- ------------------------------------------------------------
-- 数据口径的三条自我约束
-- ------------------------------------------------------------
-- 1. 症状必须能在原 illness.symptom 文本里找到出处，唯一例外是红旗症状
--    （黑便、呕血、呼吸困难、畸形、异常活动、骨擦音）——
--    它们本来就不该指望患者自己说出来。
-- 2. 用药边必须写得出 indication。写不出来的，就是当年那种
--    「阿莫西林 → 病毒性感冒」的错关联，宁可留空让人去补，也不能让它裸奔。
-- 3. 科室名严格取自 illness_category.name，不发明新科室 ——
--    模型照着念的时候，用户点进去得真的能挂上号。
-- ============================================================

