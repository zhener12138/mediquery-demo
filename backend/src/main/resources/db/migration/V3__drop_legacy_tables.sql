-- ============================================================
-- V3 · 清掉重构遗留的两张空壳表
--
-- feedback 与 sys_doctor 在项目收敛为「纯在线问诊」时就删了模块和实体，
-- 但当时只改了 init.sql —— 已经建好的库没人动它，于是这两张表一直躺在
-- 生产库里：feedback 0 行、sys_doctor 8 行种子医生，都没有任何读取方。
--
-- 为什么用 DROP 而不是留着：留着它们会持续误导后来的人——
-- 「有 sys_doctor 表，是不是该有医生功能？」「feedback 表空着，是不是反馈入口坏了？」
-- 结构应该表达意图，多余的表现在只表达"我曾经想做这些"。
--
-- 为什么写成 IF EXISTS：新库上 V1 就没建这两张表，迁移脚本要能同时
-- 服务"老库"和"新库"，不能假设表一定在。
--
-- 这一步不可逆。执行前请确认：
--   mysql> SELECT COUNT(*) FROM feedback;    -- 应为 0
--   mysql> SELECT COUNT(*) FROM sys_doctor;  -- 只有种子数据
-- 如果哪天真的要恢复人工接诊，医生表也该按新需求重新设计，
-- 而不是复活一张 2026 年 11 月之前的老结构。
-- ============================================================

DROP TABLE IF EXISTS `feedback`;
DROP TABLE IF EXISTS `sys_doctor`;
